/** Passage gardé qui s'ouvre avec un certain nombre d'insignes. */
const passage = (id: string, name: string, x: number, y: number, dir: Npc['dir'], insignes: number, look: CharacterLook, blocked: string[], open: string[]): Npc => ({
  id, name, x, y, dir, look: { kind: 'personne', look },
  script: { kind: 'gardien', condition: { insignes }, flag: `${id}:ouvert`, blocked, open },
  hideFlag: `${id}:ouvert`,
});

/** Porte d'une salle du Conseil : le garde s'efface une fois le griot vaincu. */
